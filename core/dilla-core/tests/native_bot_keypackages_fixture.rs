#![cfg(not(target_arch = "wasm32"))]

//! Test-only reproducible writer for the public WASI/DS native Bot KeyPackage fixture.
//! Run with `cargo test -p dilla-core --test native_bot_keypackages_fixture -- --ignored`.

use base64::Engine as _;
use dilla_core::bot::keypackage::{Intent, IntentResult, Resolution};
use dilla_core::cbor::decode_strict;
use dilla_core::client::ClientCore;
use dilla_core::identity::CredentialIdentity;
use dilla_core::ids::MsgId;
use dilla_core::mls::ConnHandle;
use rusqlite::Connection;
use serde_json::json;
use std::sync::{Arc, Mutex};
use std::time::{SystemTime, UNIX_EPOCH};

const INSTANCE: [u8; 16] = [0x11; 16];
const COMMUNITY: [u8; 16] = [0x22; 16];
const INSTALLATION: [u8; 16] = [0x33; 16];
const USER: [u8; 16] = [0x44; 16];

struct PendingPublic {
    umk: [u8; 32],
    ssk: [u8; 32],
    sig_umk_ssk: [u8; 64],
    device_id: [u8; 16],
    dsk: [u8; 32],
}

#[test]
#[ignore = "explicit test-only writer for the committed public native Bot fixture"]
fn write_native_bot_keypackages_fixture() {
    let conn: ConnHandle = Arc::new(Mutex::new(Connection::open_in_memory().expect("sqlite")));
    let mut core = ClientCore::open(conn).expect("open core");

    // The account/device signing keys are generated by the actual bootstrap path. Only their
    // public values and signatures are written; no secret material is included in the fixture.
    let pending = core
        .bot_bootstrap_begin(&INSTANCE, &COMMUNITY, &INSTALLATION)
        .expect("begin native Bot bootstrap");
    let PendingPublic {
        umk,
        ssk,
        sig_umk_ssk,
        device_id,
        dsk,
    } = decode_pending(&pending);
    let generated_at = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system clock")
        .as_secs();
    let final_body = core
        .bot_bootstrap_complete(&USER, "native-fixture-bot", generated_at)
        .expect("complete native Bot bootstrap");
    let (credential_raw, signed_device_list) = decode_final(&final_body);
    let credential = CredentialIdentity::decode(&credential_raw).expect("final Bot credential");
    assert_eq!(credential.user_id.as_bytes(), &USER);
    credential
        .verify_signatures(&dsk)
        .expect("public final credential signatures");

    let mut batches = Vec::with_capacity(2);
    for (operation, generation) in [(1u8, 1u64), (2, 2)] {
        let intent = Intent {
            operation_id: MsgId::from_bytes([operation; 16]),
            count: 32,
            last_resort: 1,
            expected_generation: generation,
        };
        let encoded = intent.encode().expect("intent encoding");
        let result = core
            .bot_keypackage_intent(&INSTANCE, &COMMUNITY, &INSTALLATION, &encoded)
            .expect("native Bot package generation");
        let result = IntentResult::decode(&result).expect("intent result");
        let (ordinary, fallback) = decode_upload(&result.upload_body);
        assert_eq!(ordinary.len(), 32);
        assert_eq!(result.package_refs.len(), 33);
        let ordinary = ordinary
            .into_iter()
            .zip(result.package_refs.iter().take(32))
            .map(|(kp, reference)| package_json(kp, reference, false))
            .collect::<Vec<_>>();
        let fallback = package_json(
            fallback.expect("fallback package"),
            result.package_refs.last().expect("fallback reference"),
            true,
        );
        batches.push(json!({"ordinary": ordinary, "fallback": fallback}));

        let resolution = Resolution {
            operation_id: MsgId::from_bytes([operation; 16]),
            package_refs: result.package_refs,
            outcome: 0,
            now: generated_at,
            current_generation: generation,
        };
        core.bot_keypackage_resolve(
            &INSTANCE,
            &COMMUNITY,
            &INSTALLATION,
            &resolution.encode().expect("resolution encoding"),
        )
        .expect("resolve generated batch before next one");
    }

    let fixture = json!({
        "generated_at": generated_at,
        "user_id_hex": hex::encode(USER),
        "device_id_hex": hex::encode(device_id),
        "umk_public_hex": hex::encode(umk),
        "ssk_public_hex": hex::encode(ssk),
        "sig_umk_ssk_hex": hex::encode(sig_umk_ssk),
        "dsk_public_hex": hex::encode(dsk),
        "credential_hex": hex::encode(credential_raw),
        "signed_device_list_hex": hex::encode(signed_device_list),
        "batches": batches,
    });
    let output = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../internal/mlswasi/testdata/native_bot_keypackages.json");
    std::fs::create_dir_all(output.parent().expect("fixture directory")).expect("mkdir fixture");
    std::fs::write(
        &output,
        serde_json::to_vec_pretty(&fixture).expect("JSON encoding"),
    )
    .expect("write public fixture");
    eprintln!("wrote {}", output.display());
}

fn decode_pending(raw: &[u8]) -> PendingPublic {
    decode_strict(raw, |d| {
        d.array(4)?;
        let umk = d.bytes_exact()?;
        let ssk = d.bytes_exact()?;
        let sig_umk_ssk = d.bytes_exact()?;
        d.array(5)?;
        let device_id = d.bytes_exact()?;
        let dsk = d.bytes_exact()?;
        d.uint()?; // device tier
        d.uint()?; // signer tier
        d.bytes()?; // placeholder credential
        Ok(PendingPublic {
            umk,
            ssk,
            sig_umk_ssk,
            device_id,
            dsk,
        })
    })
    .expect("bootstrap public registration")
}

fn decode_final(raw: &[u8]) -> (Vec<u8>, Vec<u8>) {
    decode_strict(raw, |d| {
        d.array(2)?;
        Ok((d.bytes()?.to_vec(), d.bytes()?.to_vec()))
    })
    .expect("final Bot identity material")
}

fn decode_upload(raw: &[u8]) -> (Vec<Vec<u8>>, Option<Vec<u8>>) {
    decode_strict(raw, |d| {
        d.array(2)?;
        let count = d.array_len()?;
        let mut ordinary = Vec::with_capacity(count);
        for _ in 0..count {
            ordinary.push(d.bytes()?.to_vec());
        }
        let fallback = d.opt_bytes()?.map(ToOwned::to_owned);
        Ok((ordinary, fallback))
    })
    .expect("native Bot KeyPackage upload body")
}

fn package_json(bytes: Vec<u8>, reference: &[u8; 32], last_resort: bool) -> serde_json::Value {
    json!({
        "key_package_base64": base64::engine::general_purpose::STANDARD.encode(bytes),
        "key_package_ref_hex": hex::encode(reference),
        "last_resort": last_resort,
    })
}
