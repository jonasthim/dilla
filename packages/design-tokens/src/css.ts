import { themes, structural, densities, type ColorTokens } from './tokens.ts';

export function kebab(key: string): string {
  return key.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').replace(/([a-zA-Z])(\d)/g, '$1-$2').toLowerCase();
}

function colorDecls(t: ColorTokens): string {
  return (Object.entries(t) as Array<[string, string | number]>).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n');
}

function densityDecls(d: (typeof densities)[keyof typeof densities]): string {
  return [
    `  --row-pad-y: ${d.rowPadY};`, `  --row-pad-x: ${d.rowPadX};`, `  --row-gap: ${d.rowGap};`,
    `  --group-gap: ${d.groupGap};`, `  --avatar-size: ${d.avatar};`, `  --line-height: ${d.lineHeight};`,
  ].join('\n');
}

function structuralDecls(): string {
  const s = structural;
  const lines = [
    `  --font-mono: ${s.font.mono};`, `  --font-serif-italic: ${s.font.serifItalic};`,
    ...Object.entries(s.text).map(([k, v]) => `  --text-${k}: ${v};`),
    ...Object.entries(s.weight).map(([k, v]) => `  --weight-${k}: ${v};`),
    `  --label-tracking: ${s.labelTracking};`, `  --label-tracking-wide: ${s.labelTrackingWide};`, `  --tracking-soft: ${s.trackingSoft};`, `  --tracking-tag: ${s.trackingTag};`,
    ...Object.entries(s.radius).map(([k, v]) => `  --r-${k}: ${v};`),
    ...Object.entries(s.opacity).map(([k, v]) => `  --opacity-${k}: ${v};`),
    ...Object.entries(s.shadow).map(([k, v]) => `  --shadow-${k.replace(/^s(\d)$/, "$1")}: ${v};`),
    ...Object.entries(s.layout).map(([k, v]) => `  --${kebab(k)}: ${v};`),
    `  --focus-ring: ${s.focusRing};`,
    ...Object.entries(s.motion).map(([k, v]) => (k === 'easeOut' ? `  --ease-out: ${v};` : `  --duration-${kebab(k)}: ${v};`)),
  ];
  return lines.join('\n');
}

/** Durations zeroed under reduced motion; `meter` is a live level readout, never zeroed. One list for the media query and `data-motion`. */
const REDUCED = ['toggle', 'track', 'press', 'fast', 'normal', 'slow', 'enter', 'badge', 'pop', 'turn', 'aside', 'bar', 'toast', 'pulse', 'caret', 'flash', 'hover', 'tab', 'spin', 'dock', 'rail-badge', 'popover', 'switch', 'switch-rise', 'focus', 'rise', 'stagger', 'stage', 'focus-in', 'beat', 'player', 'player-row', 'player-bar', 'queue', 'progress', 'scrim', 'dialog', 'profile', 'modal', 'card', 'step', 'cmd-row'];

export function renderCss(): string {
  const reduced = REDUCED.map(k => `    --duration-${k}: 0ms;`).join('\n');
  return [
    '/* Generated by packages/design-tokens (npm run build). Do not edit. */',
    `:root {\n${colorDecls(themes.signal)}\n${structuralDecls()}\n${densityDecls(densities.regular)}\n  color-scheme: dark;\n}`,
    `[data-theme="signal"] {\n${colorDecls(themes.signal)}\n  color-scheme: dark;\n}`,
    `[data-theme="light"] {\n${colorDecls(themes.light)}\n  color-scheme: light;\n}`,
    `[data-theme="high-contrast"] {\n${colorDecls(themes['high-contrast'])}\n  color-scheme: dark;\n}`,
    `@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {\n${colorDecls(themes.light).replace(/^/gm, '  ')}\n    color-scheme: light;\n  }\n}`,
    // After the colour-scheme block on purpose: a user who asks the OS for
    // more contrast gets the high-contrast theme even when the OS is light.
    // An explicit [data-theme] still wins over both, because these only
    // apply when none is set.
    `@media (prefers-contrast: more) {\n  :root:not([data-theme]) {\n${colorDecls(themes['high-contrast']).replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}`,
    `[data-density="compact"] {\n${densityDecls(densities.compact)}\n}`,
    `[data-density="regular"] {\n${densityDecls(densities.regular)}\n}`,
    `[data-density="cozy"] {\n${densityDecls(densities.cozy)}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${reduced}\n  }\n}`,
    `[data-motion="reduced"] {\n${reduced}\n}`,
    '',
  ].join('\n\n');
}
